"""
rl_gen_ref_tables.py — genere les SQL pour les tables ref :
  - ref_active_ability (depuis frida/hooks/data/ability-names.ts)
  - ref_triggered_ability (depuis frida/hooks/data/triggered-ability-names.ts)
  - ref_effect (parse depuis data/dumps/<hash>/dump.cs : enum EffectType)
  - ref_unit (depuis battles dejà en DB : SELECT DISTINCT unnest(roster_p|a))

Genere `scripts/sql/006_ref_tables.sql` + l'applique si --apply.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ABILITY_NAMES_TS = ROOT / "frida" / "hooks" / "data" / "ability-names.ts"
TRIGGERED_NAMES_TS = ROOT / "frida" / "hooks" / "data" / "triggered-ability-names.ts"
DUMP_CS = ROOT / "data" / "dumps" / "rmvdp0v56c" / "dump.cs"
SQL_OUT = ROOT / "scripts" / "sql" / "006_ref_tables.sql"


def _parse_id_name_ts(ts_path: Path) -> dict[int, str]:
    """Parse `N: "Name",` entries from a TS Record<number, string>."""
    out: dict[int, str] = {}
    text = ts_path.read_text(encoding="utf-8")
    for m in re.finditer(r'^\s*(\d+):\s*"([^"]+)"', text, re.MULTILINE):
        out[int(m.group(1))] = m.group(2)
    return out


def _parse_effect_enum_cs(cs_path: Path) -> dict[int, str]:
    """Parse `public const EffectType Name = N;` from dump.cs."""
    out: dict[int, str] = {}
    text = cs_path.read_text(encoding="utf-8", errors="ignore")
    # Locate the enum block
    m = re.search(
        r'public enum EffectType[^{]*\{(.*?)^\}', text, re.MULTILINE | re.DOTALL)
    if not m:
        return out
    body = m.group(1)
    for em in re.finditer(
            r'public const EffectType (\w+) = (-?\d+);', body):
        out[int(em.group(2))] = em.group(1)
    return out


def _sql_escape(s: str) -> str:
    return s.replace("'", "''")


def _gen_sql(actives: dict[int, str], triggered: dict[int, str],
             effects: dict[int, str]) -> str:
    lines = [
        "-- 006_ref_tables.sql -- tables de reference (abilities, effects).",
        "-- Auto-generated by rl_gen_ref_tables.py. Re-run pour regenerer.",
        "",
        "CREATE TABLE IF NOT EXISTS tacticus.ref_active_ability (",
        "  ability_id INT PRIMARY KEY,",
        "  name       TEXT NOT NULL",
        ");",
        "CREATE TABLE IF NOT EXISTS tacticus.ref_triggered_ability (",
        "  ability_id INT PRIMARY KEY,",
        "  name       TEXT NOT NULL",
        ");",
        "CREATE TABLE IF NOT EXISTS tacticus.ref_effect (",
        "  effect_id INT PRIMARY KEY,",
        "  name      TEXT NOT NULL",
        ");",
        "CREATE TABLE IF NOT EXISTS tacticus.ref_unit (",
        "  unit_id     TEXT PRIMARY KEY,   -- ex. 'orksWarboss'",
        "  faction     TEXT,                -- 'orks', 'necro', 'templ' ...",
        "  first_seen  TIMESTAMPTZ DEFAULT now()",
        ");",
        "",
        "TRUNCATE tacticus.ref_active_ability;",
        "TRUNCATE tacticus.ref_triggered_ability;",
        "TRUNCATE tacticus.ref_effect;",
        "",
    ]

    # Active
    if actives:
        lines.append("INSERT INTO tacticus.ref_active_ability (ability_id, name) VALUES")
        rows = [f"  ({i}, '{_sql_escape(n)}')" for i, n in sorted(actives.items())]
        lines.append(",\n".join(rows) + ";")
        lines.append("")

    # Triggered
    if triggered:
        lines.append("INSERT INTO tacticus.ref_triggered_ability (ability_id, name) VALUES")
        rows = [f"  ({i}, '{_sql_escape(n)}')" for i, n in sorted(triggered.items())]
        lines.append(",\n".join(rows) + ";")
        lines.append("")

    # Effects
    if effects:
        lines.append("INSERT INTO tacticus.ref_effect (effect_id, name) VALUES")
        rows = [f"  ({i}, '{_sql_escape(n)}')" for i, n in sorted(effects.items())]
        lines.append(",\n".join(rows) + ";")
        lines.append("")

    # Populate ref_unit from battles already in DB (best-effort upsert).
    lines.extend([
        "-- Populate ref_unit depuis les rosters deja ingestes.",
        "-- Le prefixe (4 premiers chars en general) sert de faction.",
        "INSERT INTO tacticus.ref_unit (unit_id, faction)",
        "SELECT DISTINCT u,",
        "       substring(u FROM '^([a-z]+)')",
        "  FROM tacticus.battle, unnest(roster_p || roster_a) u",
        " WHERE u IS NOT NULL",
        "ON CONFLICT (unit_id) DO NOTHING;",
        "",
        "-- Aussi tous les visual_id deja vus dans unit_state.",
        "INSERT INTO tacticus.ref_unit (unit_id, faction)",
        "SELECT DISTINCT visual_id,",
        "       substring(visual_id FROM '^([a-z]+)')",
        "  FROM tacticus.unit_state",
        " WHERE visual_id IS NOT NULL",
        "ON CONFLICT (unit_id) DO NOTHING;",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true",
                    help="Apply le SQL apres generation")
    args = ap.parse_args(argv[1:])

    actives = _parse_id_name_ts(ABILITY_NAMES_TS)
    triggered = _parse_id_name_ts(TRIGGERED_NAMES_TS)
    effects = _parse_effect_enum_cs(DUMP_CS)
    print(f"Parsed: actives={len(actives)} triggered={len(triggered)} effects={len(effects)}")

    sql = _gen_sql(actives, triggered, effects)
    SQL_OUT.parent.mkdir(parents=True, exist_ok=True)
    SQL_OUT.write_text(sql, encoding="utf-8")
    print(f"Wrote {SQL_OUT}")

    if args.apply:
        psql = (r"C:\Program Files\PostgreSQL\15\bin\psql.exe")
        env = os.environ.copy()
        # Lit le pwd depuis .env
        envfile = ROOT / ".env"
        pgenv: dict[str, str] = {}
        if envfile.exists():
            for line in envfile.read_text(encoding="utf-8").splitlines():
                if "=" in line and not line.startswith("#"):
                    k, v = line.split("=", 1)
                    pgenv[k.strip()] = v.strip()
        env["PGPASSWORD"] = pgenv.get("PG_PASSWORD", "")
        import subprocess
        r = subprocess.run(
            [psql, "-h", pgenv.get("PG_HOST", "localhost"),
             "-p", pgenv.get("PG_PORT", "5433"),
             "-U", pgenv.get("PG_USER", "postgres"),
             "-d", pgenv.get("PG_DATABASE", "TACTICUS"),
             "-f", str(SQL_OUT)],
            env=env, capture_output=True, text=True)
        print(r.stdout[-2000:] if len(r.stdout) > 2000 else r.stdout)
        if r.stderr:
            print("STDERR:", r.stderr, file=sys.stderr)
        return r.returncode

    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
